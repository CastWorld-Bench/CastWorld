"""One explicit protocol retry per Episode; never repair or select numerical forecasts."""

from collections import Counter
from copy import deepcopy

from pydantic import ValidationError

from .action_schema import FORECAST_FIELDS, forecast_schema
from .common import AgentError

POLICY = {
    "version": "one_protocol_retry/1.1",
    "max_alarms_per_episode": 1,
    "retry_scope": "next_action_same_intent",
    "round_accounting": "all_attempts_count; one_boundary_retry_if_needed",
    "warning_penalty_error_equivalent": 0.05,
}


def intent(action, registry):
    if action is None:
        return {"kind": "unparsed"}
    p = action.payload
    if action.action_type == "CALL_TOOL":
        calls = p.get("calls")
        if not isinstance(calls, list):
            return {"kind": "CALL_TOOL"}
        known = [
            c["tool_id"]
            for c in calls
            if isinstance(c, dict)
            and isinstance(c.get("tool_id"), str)
            and c["tool_id"] in registry.manifests
        ]
        if (
            len(calls) == 1
            and len(known) == 1
            and known[0].startswith("sandbox.")
            and known[0] not in {"sandbox.validate_forecast", "sandbox.compare_versions"}
        ):
            return {"kind": "forecast_creation"}
        return {"kind": "CALL_TOOL", "call_count": len(calls), "known_tools": known}
    result = {"kind": action.action_type}
    if (
        action.action_type == "REQUEST_STATE"
        and isinstance(p.get("section"), str)
        and p["section"]
        in {
            "summary",
            "schema",
            "history",
            "phase_history",
            "needs",
            "evidence",
            "artifact",
            "forecasts",
            "observations",
        }
    ):
        result["section"] = p["section"]
    if action.action_type == "CREATE_FORECAST":
        # A malformed or physically invalid forecast may be regenerated by another operation.
        result["kind"] = "forecast_creation"
    return result


def check_retry(action, pending):
    expected = pending["intent"]
    kind = expected["kind"]
    if kind == "unparsed":
        return
    if kind in {"forecast_creation", "missing_forecast"}:
        allowed = action.action_type == "CREATE_FORECAST" or (
            action.action_type == "CALL_TOOL"
            and isinstance(action.payload.get("calls"), list)
            and len(action.payload["calls"]) == 1
            and isinstance(action.payload["calls"][0], dict)
            and str(action.payload["calls"][0].get("tool_id", "")).startswith("sandbox.")
            and action.payload["calls"][0].get("tool_id")
            not in {
                "sandbox.validate_forecast",
                "sandbox.compare_versions",
            }
        )
    else:
        allowed = action.action_type == kind
    if not allowed:
        raise AgentError(
            "The one retry must correct the alerted action, not perform an unrelated action",
            "REPAIR_NOT_RESOLVED",
        )
    if kind == "REQUEST_STATE" and "section" in expected:
        allowed_sections = {expected["section"]}
        if expected["section"] in {"artifact", "forecasts", "observations"}:
            allowed_sections = {"artifact", "forecasts", "observations"}
        if (
            not isinstance(action.payload.get("section"), str)
            or action.payload["section"] not in allowed_sections
        ):
            raise AgentError(
                "Retry the failed resource retrieval, not an unrelated summary or schema query",
                "REPAIR_NOT_RESOLVED",
            )
    if kind == "CALL_TOOL" and "call_count" in expected:
        calls = action.payload.get("calls")
        ids = [c.get("tool_id") for c in calls if isinstance(c, dict)] if isinstance(calls, list) else []
        if (
            not all(isinstance(tid, str) for tid in ids)
            or (expected["call_count"] and len(ids) != expected["call_count"])
            or Counter(expected["known_tools"]) - Counter(ids)
        ):
            raise AgentError(
                "Retry the alerted tool batch without dropping or replacing its known tools",
                "REPAIR_NOT_RESOLVED",
            )


def feedback(action, response, exc, bundle, registry, schemas, turn, retry_intent):
    """Only public contracts and input diagnostics; no truth, model ranking, or numeric padding."""
    issues = []
    if isinstance(exc, ValidationError):
        issues = [
            {"location": ["payload", *e["loc"]], "reason": e["msg"], "type": e["type"]}
            for e in exc.errors(include_url=False, include_input=False, include_context=False)
        ]
    relevant_schemas = {}
    examples = []
    examples_calls = []
    if action is not None:
        relevant_schemas[action.action_type] = schemas[action.action_type].model_json_schema()
        if (
            action.action_type == "CREATE_FORECAST"
            and isinstance(action.payload.get("operation"), str)
            and action.payload["operation"] in FORECAST_FIELDS
        ):
            relevant_schemas[action.action_type] = forecast_schema(
                action.payload["operation"], bundle.episode.task.model_dump()
            )
        if action.action_type == "CALL_TOOL" and isinstance(action.payload.get("calls"), list):
            examples_calls = []
            for i, call in enumerate(action.payload["calls"]):
                if (
                    not isinstance(call, dict)
                    or not isinstance(call.get("tool_id"), str)
                    or call["tool_id"] not in registry.manifests
                ):
                    continue
                tid = call["tool_id"]
                relevant_schemas[tid] = registry.manifests[tid]["input_schema"]
                try:
                    registry.validate(tid, call.get("arguments", {}))
                except ValidationError as error:
                    issues.extend(
                        {
                            "location": ["payload", "calls", i, "arguments", *e["loc"]],
                            "reason": e["msg"],
                            "type": e["type"],
                        }
                        for e in error.errors(include_url=False, include_input=False, include_context=False)
                    )
                except (AgentError, TypeError, ValueError):
                    pass
                if tid.startswith("model."):
                    task = bundle.episode.task
                    args = {
                        "frequency": task.frequency,
                        "forecast_gap": task.forecast_gap,
                        "horizon_length": task.horizon_length,
                    }
                    examples_calls.append(
                        {
                            "call_id": f"retry_{i}",
                            "tool_id": tid,
                            "arguments": args,
                            "purpose": "Obtain the selected model's forecast for this task window",
                        }
                    )
            if examples_calls and len(examples_calls) == len(action.payload["calls"]):
                examples.append(
                    {"action_type": "CALL_TOOL", "state_version": turn, "payload": {"calls": examples_calls}}
                )
    p = action.payload if action is not None else {}
    from .providers import protocol_examples

    expected = retry_intent["kind"]
    template_kind = (
        "CREATE_FORECAST" if expected in {"forecast_creation", "missing_forecast", "unparsed"} else expected
    )
    if template_kind != "CALL_TOOL":
        for template in protocol_examples({"state_version": turn})["actions"]:
            if template["action_type"] != template_kind:
                continue
            if (
                template_kind == "CREATE_FORECAST"
                and isinstance(p.get("operation"), str)
                and p["operation"] in FORECAST_FIELDS
                and template["payload"].get("operation") != p["operation"]
            ):
                continue
            if (
                expected == "REQUEST_STATE"
                and "section" in retry_intent
                and template["payload"]["section"] != retry_intent["section"]
            ):
                continue
            if template.get("payload", {}).get("section") == "artifact":
                template["payload"]["path"] = ["<key actually present in this artifact>"]
            examples.append(template)
    if not examples:
        if expected == "CALL_TOOL":
            calls = action.payload.get("calls") if action else None
            calls = calls if isinstance(calls, list) and calls else [{}]
            example_calls = []
            for i, c in enumerate(calls):
                tid = c.get("tool_id") if isinstance(c, dict) else None
                tid = (
                    tid
                    if isinstance(tid, str) and tid in registry.manifests
                    else "<choose the intended tool from the catalog>"
                )
                schema = registry.manifests.get(tid, {}).get("input_schema", {})
                args = {
                    name: f"<supply {name} with the type required by its inline schema>"
                    for name in schema.get("required", [])
                }
                example_calls.append(
                    {
                        "call_id": f"retry_{i}",
                        "tool_id": tid,
                        "arguments": args,
                        "purpose": "<your original information need>",
                    }
                )
            examples.append(
                {"action_type": "CALL_TOOL", "state_version": turn, "payload": {"calls": example_calls}}
            )
        elif action is not None:
            schema = schemas[action.action_type].model_json_schema()
            examples.append(
                {
                    "action_type": action.action_type,
                    "state_version": turn,
                    "payload": {
                        k: f"<supply {k} according to the inline schema>" for k in schema.get("required", [])
                    },
                }
            )
    if isinstance(p.get("scored_values"), list):
        issues.append(
            {
                "location": ["payload", "scored_values"],
                "received_count": len(p["scored_values"]),
                "required_count": bundle.episode.task.horizon_length,
            }
        )
    return {
        "reason": response["message"],
        "code": response["code"],
        "issues": issues or [{"location": ["action"], "reason": response["message"]}],
        "schemas": relevant_schemas,
        "correct_format_examples": examples,
        "selected_model_call_fragments": examples_calls,
        "example_notice": "Examples show formats, not prescribed predictions. Replace ALL <...> placeholders with correctly typed values from the inline schemas. Model-call fragments are individual calls, NOT a replacement for an entire mixed batch. Do not perform an unrelated schema query instead of correcting the alerted action. Never copy read-only output metadata into input.",
        "forecast_contract": {
            "scored_count": bundle.episode.task.horizon_length,
            "gap_count": bundle.episode.task.forecast_gap,
            "unit": bundle.episode.task.target_unit,
            "timeline": "episode.forecast_timeline.scored_timestamps",
            "numeric_policy": "Each scored timestamp needs one finite number; no automatic padding, truncation or clipping.",
        },
        "hint": response.get("recovery", {}).get("hint", "Submit a complete legal Agent forecast."),
    }


def open_alarm(state, action, response, exc, bundle, registry, schemas, turn, *, missing=False):
    alarm = {
        "alarm_id": "protocol_alarm_1",
        "turn": turn,
        "code": response["code"],
        "message": response["message"],
        "status": "pending",
        "retry_turn": None,
        "intent": {"kind": "missing_forecast"} if missing else intent(action, registry),
    }
    if (
        action is not None
        and action.action_type == "FINALIZE"
        and not any(v["kind"] != "model_candidate" for v in state["forecasts"].values())
    ):
        alarm["intent"] = {"kind": "missing_forecast"}
    state["protocol_alarms"].append(alarm)
    state["repair_pending"] = deepcopy(alarm)
    response["protocol_alarm"] = {
        **alarm,
        "instruction": "This Episode has ONE protocol-repair opportunity. Correct this action on your NEXT response, even if ordinary rounds_remaining is zero. Existing progress is preserved. A successful correction counts only as an alarm; a failed correction is one scored error, with no further exemption. All raw attempts and time remain audited.",
        "feedback": feedback(action, response, exc, bundle, registry, schemas, turn, alarm["intent"]),
    }
    response["recovery"] = {
        "notice": "Rejected action made no changes. Correct the same intent on the next action.",
        "hint": "Use the inline protocol_alarm.feedback schemas and examples; do not spend this one retry on a schema query.",
    }
    response["protocol_alarm"]["feedback"]["hint"] = response["recovery"]["hint"]


def close_alarm(state, turn, success):
    alarm = state["protocol_alarms"][0]
    alarm.update(status="recovered" if success else "failed", retry_turn=turn)
    state["repair_pending"] = None
